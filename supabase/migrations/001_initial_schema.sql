-- 6. ATOMIC CHECKOUT & INVENTORY RPC (TRANSACTIONAL SAFETY)
-- ==============================================================================
CREATE OR REPLACE FUNCTION place_order_transaction(
    p_order_number VARCHAR,
    p_user_id BIGINT,
    p_customer_name VARCHAR,
    p_email VARCHAR,
    p_phone VARCHAR,
    p_address TEXT,
    p_city VARCHAR,
    p_state VARCHAR,
    p_pincode VARCHAR,
    p_delivery_charge NUMERIC,
    p_payment_method VARCHAR,
    p_items JSONB
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_order_id BIGINT;
    v_item JSONB;
    v_product_id BIGINT;
    v_req_qty INT;
    v_actual_price NUMERIC;
    v_actual_stock INT;
    v_actual_name VARCHAR;
    v_calculated_subtotal NUMERIC := 0.00;
    v_calculated_total NUMERIC := 0.00;
    v_item_subtotal NUMERIC;
BEGIN
    -- Validate items list
    IF p_items IS NULL OR jsonb_array_length(p_items) = 0 THEN
        RAISE EXCEPTION 'Order items list cannot be empty';
    END IF;

    -- Validate user existence
    IF NOT EXISTS (SELECT 1 FROM users WHERE id = p_user_id) THEN
        RAISE EXCEPTION 'User ID % does not exist', p_user_id;
    END IF;

    -- First pass: Row-level locking (FOR UPDATE) to prevent overselling & race conditions
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        v_product_id := (v_item->>'product_id')::BIGINT;
        v_req_qty := (v_item->>'quantity')::INT;

        IF v_req_qty <= 0 THEN
            RAISE EXCEPTION 'Invalid quantity % for product ID %', v_req_qty, v_product_id;
        END IF;

        SELECT id, name, price, stock 
        INTO v_product_id, v_actual_name, v_actual_price, v_actual_stock
        FROM products
        WHERE id = v_product_id
        FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Product with ID % not found', v_product_id;
        END IF;

        IF v_actual_stock < v_req_qty THEN
            RAISE EXCEPTION 'Insufficient stock for product "%". Requested: %, Available: %', v_actual_name, v_req_qty, v_actual_stock;
        END IF;

        v_item_subtotal := v_actual_price * v_req_qty;
        v_calculated_subtotal := v_calculated_subtotal + v_item_subtotal;
    END LOOP;

    v_calculated_total := v_calculated_subtotal + COALESCE(p_delivery_charge, 0.00);

    -- Insert Order record with validated trusted server totals
    INSERT INTO orders (
        order_number, user_id, customer_name, email, phone,
        address, city, state, pincode,
        subtotal, delivery_charge, total_amount, payment_method, status, created_at
    ) VALUES (
        p_order_number, p_user_id, p_customer_name, p_email, p_phone,
        p_address, p_city, p_state, p_pincode,
        v_calculated_subtotal, COALESCE(p_delivery_charge, 0.00), v_calculated_total, p_payment_method, 'Pending', timezone('utc'::text, now())
    ) RETURNING id INTO v_order_id;

    -- Second pass: insert order items and decrement stock atomically
    FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        v_product_id := (v_item->>'product_id')::BIGINT;
        v_req_qty := (v_item->>'quantity')::INT;

        SELECT name, price INTO v_actual_name, v_actual_price
        FROM products WHERE id = v_product_id;

        v_item_subtotal := v_actual_price * v_req_qty;

        INSERT INTO order_items (
            order_id, product_id, product_name, quantity, unit_price, subtotal
        ) VALUES (
            v_order_id, v_product_id, v_actual_name, v_req_qty, v_actual_price, v_item_subtotal
        );

        UPDATE products
        SET stock = stock - v_req_qty,
            updated_at = timezone('utc'::text, now())
        WHERE id = v_product_id;
    END LOOP;

    RETURN jsonb_build_object(
        'success', true,
        'order_id', v_order_id,
        'order_number', p_order_number,
        'subtotal', v_calculated_subtotal,
        'delivery_charge', COALESCE(p_delivery_charge, 0.00),
        'total_amount', v_calculated_total
    );
END;
$$;

-- ==============================================================================
-- 7. SECURE SERVER-SIDE QUERY HELPERS (RESTRICTED TO SERVICE ROLE)
-- ==============================================================================
CREATE OR REPLACE FUNCTION run_sql_query(query_text TEXT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    result JSONB;
BEGIN
    EXECUTE 'SELECT COALESCE(jsonb_agg(to_jsonb(t)), ''[]''::jsonb) FROM (' || query_text || ') t' INTO result;
    RETURN COALESCE(result, '[]'::jsonb);
END;
$$;

CREATE OR REPLACE FUNCTION run_sql_command(cmd_text TEXT)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_rows INTEGER;
BEGIN
    EXECUTE cmd_text;
    GET DIAGNOSTICS v_rows = ROW_COUNT;
    RETURN v_rows;
END;
$$;

REVOKE EXECUTE ON FUNCTION run_sql_query(TEXT) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION run_sql_query(TEXT) FROM anon;
REVOKE EXECUTE ON FUNCTION run_sql_query(TEXT) FROM authenticated;
GRANT EXECUTE ON FUNCTION run_sql_query(TEXT) TO service_role;

